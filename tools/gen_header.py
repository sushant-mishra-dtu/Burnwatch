"""Write hls/config.h from detector/config.py, so the HLS testbench and the golden model share one source.

    python tools/gen_header.py            # writes hls/config.h
    python tools/gen_header.py --check    # exit 1 if hls/config.h is out of date

The core reads every tunable from AXI-Lite registers at run time; the CFG_* defaults are for the testbench.
"""
import argparse
import os
import sys
from dataclasses import fields

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from detector import config  # noqa: E402
from detector.config import REGISTER_FIELDS, Params  # noqa: E402

OUT = os.path.join(ROOT, "hls", "config.h")


def render():
    p = Params()
    tile = config.TILE_FULL
    lines = [
        "// Generated by tools/gen_header.py from detector/config.py. Do not edit; rerun the script.",
        "#ifndef BURNWATCH_CONFIG_H",
        "#define BURNWATCH_CONFIG_H",
        "",
        f"#define SPEC_VERSION {config.SPEC_VERSION}",
        "",
        "// Geometry (FULL mode)",
        f"#define IMG_W {config.IMG_W}",
        f"#define IMG_H {config.IMG_H}",
        f"#define TILE {tile}",
        f"#define LOG2_TILE_PIXELS {2 * (tile.bit_length() - 1)}",
        f"#define TILES_X {config.TILES_X}",
        f"#define TILES_Y {config.TILES_Y}",
        f"#define N_TILES {config.N_TILES}",
        "",
        "// Register defaults, in register order (testbench only; the core takes them at run time)",
    ]
    lines += [f"#define CFG_{name} {getattr(p, name)}" for name in REGISTER_FIELDS]
    lines += ["", "// Caller-side (not registers)"]
    lines += [f"#define CFG_{f.name} {getattr(p, f.name)}" for f in fields(p) if f.name not in REGISTER_FIELDS]
    lines += ["", "#endif  // BURNWATCH_CONFIG_H", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description="write hls/config.h from detector/config.py")
    ap.add_argument("--check", action="store_true", help="only check that hls/config.h is current")
    a = ap.parse_args()
    text = render()
    if a.check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit(f"{OUT} is out of date: run python tools/gen_header.py")
        print(f"{OUT} is current")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
